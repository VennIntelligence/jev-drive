#!/usr/bin/env python3
"""Step 0 read-out of the ONPOL-NUPLAN lane: JAPSnoY and APY10m10-AB with four seeds against P2H10-F (2 seeds) and P2H10S-F (4 seeds) on the 1491
public nuPlan AlpaSim scenes. A thin wrapper: stored reads, scene helpers and bootstraps are joint1_report.py's (sources(): the JOINT-1 reruns of
seeds 0-1, compiled driver path), the seeds 2-3 reads come from this chain's manifest ($DATA_DIR/runs/onpol_nuplan/seeds4/loop/manifest.json).

  .venv/bin/python experiments/onpol_nuplan/scripts/seeds4_report.py --out DIR      (box)
Writes DIR/{seeds4_report.md, seeds4_stats.json, seeds4_per_scene.csv}.
"""
import sys as _sys, pathlib as _pl  # noqa: E401
_H = _pl.Path(__file__).resolve()
_sys.path[:0] = [str(_H.parents[2] / "alpasim" / "scripts"), str(_H.parents[2] / "body1" / "scripts"), str(_H.parents[3])]
import argparse  # noqa: E402
import csv  # noqa: E402
import json  # noqa: E402

import numpy as np  # noqa: E402

import c0b_report as R  # noqa: E402
import joint1_report as J  # noqa: E402
import stop_report as SR  # noqa: E402

CLS, SHORT = J.CLS, J.SHORT
W = J.DATA / "runs/onpol_nuplan/seeds4"
REC = {"P2H10-F": 2, "P2H10S-F": 4, "JAPSnoY": 4, "APY10m10-AB": 4}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    out = _pl.Path(ap.parse_args().out)
    out.mkdir(parents=True, exist_ok=True)
    CH, fam_ok = J.checks()
    src = J.sources(fam_ok)
    new = J.man(W / "loop/manifest.json")
    for t in ("JAPSnoY", "APY10m10-AB"):
        for s in (2, 3):
            src[f"{t}-s{s}"] = new.get(f"{t}-s{s}", []) + new.get(f"{t}-s{s}@fresh", []) + new.get(f"{t}-s{s}@new", [])
    tags = {r: [f"{r}-s{s}" for s in range(n)] for r, n in REC.items()}
    need = [t for v in tags.values() for t in v]
    D = {t: R.load_driver(src[t]) for t in need if src.get(t)}
    scenes = sorted(set().union(*(set((J.RA / "c0b/lists" / f"{x}.txt").read_text().split()) for x in ("chunk0", "chunk1", "chunk2", "cf1fresh", "ot3new"))))
    assert len(scenes) == 1491, len(scenes)
    have = {t for t, d in D.items() if all(s in d[0] for s in scenes)}
    miss = {t: (len([s for s in scenes if s not in D[t][0]]) if t in D else 1491) for t in need if t not in have}
    A = {t: J.Arm(D[t][0], D[t][3], scenes) for t in have}
    logs = np.array([R.log_of(s) for s in scenes])
    T = SR.turns()
    turn = np.array([T.get(s.rsplit("-", 1)[1], np.nan) for s in scenes])
    g45 = np.abs(turn) > 45
    K = [r for r in REC if all(t in A for t in tags[r])]
    mean = lambda r, f: np.mean([f(A[t]) for t in tags[r]], 0)  # noqa: E731
    sc = {r: mean(r, lambda x: x.sc) for r in K}
    z3 = {r: mean(r, lambda x: x.z()) for r in K}
    zc = {r: {c: mean(r, lambda x, c=c: x.z((c,))) for c in CLS} for r in K}
    zco = {r: zc[r]["collision_at_fault"] + zc[r]["offroad"] for r in K}
    L = ["# ONPOL-NUPLAN step 0: four seeds of JAPSnoY and APY10m10-AB (generated by seeds4_report.py; do not edit)", "",
         f"1491 scenes, {len(set(logs))} logs, {int(g45.sum())} turning more than 45 deg. Incomplete tags (scenes missing): {miss or 'none'}. "
         f"Driver families whose stored compiled reads are used: {', '.join(f for f, ok in fam_ok.items() if ok) or 'none'}. Seeds 0-1 of JAPSnoY / APY10m10-AB / "
         "P2H10-F / P2H10S-F are joint1_report.sources() (JOINT-1 reruns, compiled driver path), seeds 2-3 of the two new recipes this chain's loop.", "",
         "## Per recipe (zero counts, at-fault events, slow and progress are means over the recipe's seeds)", "",
         "| recipe | seeds | per-seed means | seed mean [95 % CI, logs] | zeros (3 classes) | collision / offroad / corridor | at-fault zeros (collision + offroad) | "
         "at-fault events | slow | progress |", "|:--|--:|:--|:--|--:|:--|--:|--:|--:|--:|"]
    st = {"missing": miss, "arms": {}, "diff": {}, "flips": []}
    for r in K:
        m = R.ci(sc[r], logs)
        seeds = [float(A[t].sc.mean()) for t in tags[r]]
        cz = {SHORT[c]: float(zc[r][c].sum()) for c in CLS}
        ev = float(np.mean([A[t].ev.sum() for t in tags[r]]))
        slow = float(np.mean([((A[t].sc > 0) & (A[t].sc < 1)).sum() for t in tags[r]]))
        prog = float(np.mean([A[t].prog.mean() for t in tags[r]]))
        st["arms"][r] = dict(tags=tags[r], seeds=seeds, mean=m, zeros3=float(z3[r].sum()), classes=cz, atfault=float(zco[r].sum()), events=ev, slow=slow, progress=prog,
                             per_seed_zeros={t: {SHORT[c]: int(A[t].z((c,)).sum()) for c in CLS} for t in tags[r]})
        L.append(f"| {r} | {len(tags[r])} | {' / '.join(f'{x:.4f}' for x in seeds)} | {R.fmt(m)} | {z3[r].sum():g} | {cz['collision']:g} / {cz['offroad']:g} / {cz['corridor']:g} | "
                 f"{zco[r].sum():g} | {ev:g} | {slow:g} | {prog:.4f} |")
    L += ["", "Per-seed zeros (collision / offroad / corridor): " + "; ".join(
        f"{t} {'/'.join(str(v) for v in d.values())}" for r in K for t, d in st["arms"][r]["per_seed_zeros"].items()), ""]
    # paired differences on the seed means
    pairs = [(a, b) for a in ("JAPSnoY", "APY10m10-AB") for b in ("P2H10-F", "P2H10S-F") if a in K and b in K]
    if "JAPSnoY" in K and "APY10m10-AB" in K:
        pairs.append(("JAPSnoY", "APY10m10-AB"))
    if "P2H10S-F" in K and "P2H10-F" in K:
        pairs.append(("P2H10S-F", "P2H10-F"))
    L += ["## Paired differences (arm - reference, per-scene seed means; zeros: sum over scenes with scene-bootstrap CI, B 10 000; mean score: by-log CI)", "",
          "| arm - reference | mean score [CI logs] | zeros 3 classes [CI scenes] | at-fault zeros [CI scenes] | corridor zeros [CI scenes] | zeros 3 classes [CI logs] |", "|:--|:--|:--|:--|:--|:--|"]
    for a, b in pairs:
        d = R.ci(sc[a] - sc[b], logs)
        z, zo, zr = J.sboot(z3[a] - z3[b]), J.sboot(zco[a] - zco[b]), J.sboot(zc[a]["left_corridor_laterally"] - zc[b]["left_corridor_laterally"])
        zl = R.ci(z3[a] - z3[b], logs)
        st["diff"][f"{a} - {b}"] = dict(score=d, zeros3=z, atfault=zo, corridor=zr, zeros3_logs=[x * 1491 for x in zl])
        L.append(f"| {a} - {b} | {J.f4(d)} | {J.fz(z)} | {J.fz(zo)} | {J.fz(zr)} | {zl[1] * 1491:+.1f}, {zl[2] * 1491:+.1f} |")
    # the same for seeds 0-1 only (the earlier two-seed read), JAPSnoY / APY vs P2H10-F
    if "P2H10-F" in K:
        L += ["", "Seeds 0-1 only (the two-seed reads, for comparison with the four-seed ones above):", "", "| arm (s0, s1) - P2H10-F | mean score [CI logs] | zeros 3 classes [CI scenes] |", "|:--|:--|:--|"]
        for a in ("JAPSnoY", "APY10m10-AB"):
            if a in K:
                s2 = np.mean([A[t].sc for t in tags[a][:2]], 0)
                z2 = np.mean([A[t].z() for t in tags[a][:2]], 0)
                L.append(f"| {a} | {J.f4(R.ci(s2 - sc['P2H10-F'], logs))} | {J.fz(J.sboot(z2 - z3['P2H10-F']))} |")
    # fixed vs broken: share of seeds with a zero; fixed = reference zero in all its seeds and arm in none, broken = the reverse
    L += ["", "## Fixed vs broken (per scene: fraction of seeds with a zero; fixed = reference all seeds zero, arm none; broken = reverse; partial = other changes)", "",
          "| arm vs reference | class | fixed | broken | partial (better / worse) | zeros reference -> arm |", "|:--|:--|--:|--:|:--|:--|"]
    for a, b in pairs:
        for name, cl in (("three classes", CLS), ("collision + offroad", CLS[:2]), ("corridor", CLS[2:])):
            fa, fb = (np.mean([A[t].z(cl) for t in tags[x]], 0) for x in (a, b))
            fx, br = int(((fb == 1) & (fa == 0)).sum()), int(((fb == 0) & (fa == 1)).sum())
            pb, pw = int(((fa < fb) & ~((fb == 1) & (fa == 0))).sum()), int(((fa > fb) & ~((fb == 0) & (fa == 1))).sum())
            st["flips"].append(dict(arm=a, ref=b, cls=name, fixed=fx, broken=br, partial_better=pb, partial_worse=pw, ref_zeros=float(fb.sum()), arm_zeros=float(fa.sum())))
            L.append(f"| {a} vs {b} | {name} | {fx} | {br} | {pb} / {pw} | {fb.sum():g} -> {fa.sum():g} |")
    with (out / "seeds4_per_scene.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        ts = sorted(A)
        w.writerow(["scene", "log", "turn4s_deg"] + [f"{t}|{c}" for t in ts for c in ("score", "zero_class", "atfault_events", "progress")])
        for i, s in enumerate(scenes):
            w.writerow([s, logs[i], "" if np.isnan(turn[i]) else round(float(turn[i]), 1)] +
                       [x for t in ts for x in (round(float(A[t].sc[i]), 6), A[t].cls[i], A[t].ev[i], round(float(A[t].prog[i]), 4))])
    (out / "seeds4_stats.json").write_text(json.dumps(st, indent=1, default=float))
    (out / "seeds4_report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
