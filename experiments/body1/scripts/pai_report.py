#!/usr/bin/env python3
"""BODY1 note (j): the descriptive PAI read. Descriptive only: it cannot promote any arm.
  python3 pai_report.py --runs $DATA_DIR/runs/body1/pai/runs --pai2 $DATA_DIR/runs/alpasim/pai2/base --fix1 $DATA_DIR/runs/alpasim/fix1/paibox/runs \
      --chunks experiments/alpasim/results/pai/chunks --out experiments/body1/results/pai --fig experiments/body1/figs/pai
Sources: serving (i) plain: base P2H10-F-s0/1 = PAI2 runs, other tags = <runs>/<tag>_i_<chunk>; serving (ii) JEV_VCONT=1.0 JEV_LEAD=1: base s0/s1 = FIX1's
arm "ab", other tags = <runs>/<tag>_ii_<chunk>. 60 scenes = chunks a10 b1 b2a b2b e1 e2 (one rollout per scene, tag and serving).
Arm minus base is paired by seed index and scene; scene-bootstrap 95 % CI (10 000 draws, seed 0). Null = the same differences between base seeds.
"""
import argparse
import csv
import itertools
import json
from pathlib import Path

import numpy as np

CH = ("a10", "b1", "b2a", "b2b", "e1", "e2")
FAIL = (("collision_at_fault", "at-fault collision"), ("offroad", "offroad"), ("left_corridor_laterally", "corridor"))
SERV = {"i": "plain", "ii": "VCONT=1.0 LEAD=1"}
ALPAMAYO1 = 0.5033
BASE, FAMS = "P2H10-F", {"P2H10S-F": "shape-only hinge (P2H10S)", "P2H10B-F": "boundary-weighted (P2H10B)"}


def load(d):
    try:
        return {r["clipgt_id"]: r for r in json.loads((Path(d) / "aggregate/results-summary.json").read_text())["rollouts"]}
    except Exception:
        return None


def cls(r):
    return next((n for k, n in FAIL if r["score_metrics"].get(k)), "other" if r["score"] == 0 else "")


def boot(d, rng):
    ix = rng.integers(0, len(d), (10000, len(d)))
    return [float(v) for v in np.percentile(d[ix].mean(1), [2.5, 97.5])]


def main():
    ap = argparse.ArgumentParser()
    for k in ("runs", "pai2", "fix1", "chunks", "out", "fig"):
        ap.add_argument("--" + k, required=True)
    a = ap.parse_args()
    out, fig = Path(a.out), Path(a.fig)
    out.mkdir(parents=True, exist_ok=True)
    fig.mkdir(parents=True, exist_ok=True)
    scenes = [s for c in CH for s in (Path(a.chunks) / f"{c}.txt").read_text().split()]
    D, miss = {}, []
    tags = sorted({p.name.split("_")[0] for p in Path(a.runs).glob("*_*_*")}) + [f"{BASE}-s{i}" for i in (0, 1)]
    for t in dict.fromkeys(tags):
        for v in SERV:
            R = {}
            for c in CH:
                if t in (f"{BASE}-s0", f"{BASE}-s1"):
                    d = Path(a.pai2) / f"{c}_s{t[-1]}" if v == "i" else Path(a.fix1) / f"ab_{c}_s{t[-1]}"
                else:
                    d = Path(a.runs) / f"{t}_{v}_{c}"
                r = load(d)
                if r is None:
                    miss.append(f"{t} {v} {c}")
                else:
                    R |= r
            if R:
                D[t, v] = R
    score = lambda k: np.array([D[k][s]["score"] if k in D and s in D[k] else np.nan for s in scenes])  # noqa: E731
    full = lambda k: not np.isnan(score(k)).any()  # noqa: E731
    rng = np.random.default_rng(0)
    L = ["# generated by scripts/pai_report.py; descriptive read, cannot promote anything", "",
         "Missing chunk stacks: " + (", ".join(miss) or "none"), ""]
    rows = []
    for v, vn in SERV.items():
        L += [f"## Serving ({v}) {vn}", "", "| tag | scenes | mean score | zeros | at-fault collision | offroad | corridor | other | slow (0 < score < 1) | mean progress (progress_clipped_rel) |",
              "|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
        for (t, vv) in sorted(D):
            if vv != v:
                continue
            x = score((t, v))
            ok = ~np.isnan(x)
            rs = [D[t, v][s] for s in scenes if s in D[t, v]]
            z = {n: sum(cls(r) == n for r in rs) for _, n in FAIL} | {"other": sum(cls(r) == "other" for r in rs)}
            pr = float(np.nanmean([np.nan if r["score_metrics"].get("progress_clipped_rel") is None else r["score_metrics"]["progress_clipped_rel"] for r in rs]))
            row = dict(tag=t, serving=v, n=int(ok.sum()), mean=float(x[ok].mean()), zeros=int((x[ok] == 0).sum()), **z, slow=int(((x[ok] > 0) & (x[ok] < 1)).sum()), progress=pr)
            rows.append(row)
            L.append(f"| {t} | {row['n']} | {row['mean']:.4f} | {row['zeros']} | {z['at-fault collision']} | {z['offroad']} | {z['corridor']} | {z['other']} | {row['slow']} | {pr:.3f} |")
        L += [f"| alpamayo1 (organisers' reference, 441 scenes) | | {ALPAMAYO1} | | | | | | | |", ""]
    with (out / "pai_by_tag.csv").open("w") as f:
        w = csv.DictWriter(f, rows[0].keys())
        w.writeheader()
        w.writerows(rows)
    # paired differences and the null
    P, stats = [], {}
    for v, vn in SERV.items():
        L += [f"## Paired differences, serving ({v}) {vn}", "",
              "Difference = arm minus base of the same seed index, same scenes, in mean score; CI = scene bootstrap. Null rows: base seed i minus base seed j.", "",
              "| comparison | scenes | difference | 95 % CI | outside the base-pair differences |", "|:--|--:|--:|:--|:--|"]
        bs = [i for i in range(4) if full((f"{BASE}-s{i}", v))]
        null = []
        for i, j in itertools.combinations(bs, 2):
            d = score((f"{BASE}-s{j}", v)) - score((f"{BASE}-s{i}", v))
            ci = boot(d, rng)
            null.append(abs(d.mean()))
            L.append(f"| null: base s{j} - base s{i} | {len(d)} | {d.mean():+.4f} | [{ci[0]:+.4f}, {ci[1]:+.4f}] | |")
            P.append(dict(serving=v, comparison=f"null s{j}-s{i}", n=len(d), diff=float(d.mean()), lo=ci[0], hi=ci[1]))
        mx = max(null) if null else float("nan")
        for fam, fn in FAMS.items():
            sd = [i for i in range(4) if full((f"{fam}-s{i}", v)) and full((f"{BASE}-s{i}", v))]
            for i in sd:
                d = score((f"{fam}-s{i}", v)) - score((f"{BASE}-s{i}", v))
                ci = boot(d, rng)
                P.append(dict(serving=v, comparison=f"{fam}-s{i} - base s{i}", n=len(d), diff=float(d.mean()), lo=ci[0], hi=ci[1]))
                L.append(f"| {fam}-s{i} - base s{i} | {len(d)} | {d.mean():+.4f} | [{ci[0]:+.4f}, {ci[1]:+.4f}] | {'yes' if abs(d.mean()) > mx else 'no'} (max |null| {mx:.4f}) |")
            if len(sd) > 1:
                d = np.mean([score((f"{fam}-s{i}", v)) - score((f"{BASE}-s{i}", v)) for i in sd], 0)
                ci = boot(d, rng)
                stats[fam, v] = dict(seeds=sd, diff=float(d.mean()), ci=ci)
                P.append(dict(serving=v, comparison=f"{fam} seed-mean (s{','.join(map(str, sd))}) - base", n=len(d), diff=float(d.mean()), lo=ci[0], hi=ci[1]))
                L.append(f"| {fam} seed mean (s{','.join(map(str, sd))}) - base same seeds | {len(d)} | {d.mean():+.4f} | [{ci[0]:+.4f}, {ci[1]:+.4f}] | {'yes' if abs(d.mean()) > mx else 'no'} (max |null| {mx:.4f}) |")
        L.append("")
    with (out / "pai_paired.csv").open("w") as f:
        w = csv.DictWriter(f, P[0].keys())
        w.writeheader()
        w.writerows(P)
    (out / "pai_paired.json").write_text(json.dumps({"|".join(k): v for k, v in stats.items()}, indent=1))
    (out / "pai_tables.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    # figure: per-seed scores, base spread band
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    f, ax = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
    for k, (v, vn) in zip(ax, SERV.items()):
        bm = [r["mean"] for r in rows if r["serving"] == v and r["tag"].startswith(BASE)]
        if bm:
            k.axhspan(min(bm), max(bm), color="0.85", label="base seed spread")
        for xi, (pre, lab, col) in enumerate([(BASE, "base", "0.3"), ("P2H10S-F", "P2H10S", "C0"), ("P2H10B-F", "P2H10B", "C1")]):
            r = sorted((r for r in rows if r["serving"] == v and r["tag"].startswith(pre + "-s")), key=lambda r: r["tag"])
            k.scatter([xi] * len(r), [q["mean"] for q in r], c=col, zorder=3)
            for q in r:
                k.annotate("s" + q["tag"][-1], (xi, q["mean"]), xytext=(6, 0), textcoords="offset points", fontsize=8)
        k.axhline(ALPAMAYO1, ls="--", c="C3", label="alpamayo1 0.5033 (441 scenes)")
        k.set_xticks(range(3), ["base P2H10", "P2H10S", "P2H10B"])
        k.set_title(f"serving ({v}) {vn}")
        k.set_xlim(-0.5, 2.6)
    ax[0].set_ylabel("mean PAI score, 60 scenes")
    ax[0].legend(loc="upper left", fontsize=8)
    f.tight_layout()
    f.savefig(fig / "pai_per_seed.png", dpi=130)


if __name__ == "__main__":
    main()
