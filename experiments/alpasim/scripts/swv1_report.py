#!/usr/bin/env python3
"""Lane SWV1 report pieces (after swv1_a.py, swv1_bc.py): results/swerve/classes.md and the figures in figs/swerve/.

  swv1_report.py   -> results/swerve/classes.md, figs/swerve/{fig1_classes, fig2_ceiling_signals, ex_*}.png
Bird's-eye examples: grey = recorded objects at the decision time, orange = the struck object (outline: where it is at the planned
contact), blue band = the served plan's swept ego box, red box = the first planned ego pose that intersects, green line = the shipped
weights' plan on the same tokens, dashed = logged path, black = the path the ego drove. Simulator state is drawn as a label only."""
import csv
import pickle
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import shapely  # noqa: E402

import swv1_lib as S  # noqa: E402

CL = S.CL
OUT = S.RES / "swerve"
FIG = S.ROOT / "experiments/alpasim/figs/swerve"
COL = {"i": "#2a78d6", "ii": "#eb6834", "iii": "#1baf7a", "iv": "#eda100", "v": "#e87ba4"}
NAME = {"i": "(i) straight into an in-path object", "ii": "(ii) manoeuvre, planned sweep intersects", "iii": "(iii) manoeuvre, planned sweep clears",
        "iv": "(iv) drift, no manoeuvre", "v": "(v) other (object moves into the ego)"}
INK, MUTE, SURF = "#1a1a19", "#6b6a63", "#fcfcfb"
GROUPS = [("nuPlan, P2H10-F s0 + s1", ("P2H10-F-s0", "P2H10-F-s1")), ("nuPlan, APY10m10-AB s0 + s1", ("APY10m10-AB-s0", "APY10m10-AB-s1")),
          ("PAI, P2H10-F-s0 baseline", ("pai-base",)), ("PAI, re-timed arm v1", ("pai-v1",))]
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTE, "axes.labelcolor": INK, "xtick.color": MUTE, "ytick.color": MUTE, "figure.facecolor": SURF,
                     "axes.facecolor": SURF, "savefig.facecolor": SURF, "axes.spines.top": False, "axes.spines.right": False})


def clips():
    n = {(r["set"], r["scene"]): r["id"] for r in csv.DictReader(open(S.RES / "collisions/nuplan_clip_cases.csv"))}
    p = {("pai-base", r["scene"]): r["file"].split("_")[1] for r in csv.DictReader(open(S.RES / "collisions/pai_clip_cases.csv")) if r["file"].startswith("pai_p")}
    return {**n, **p}


def f(r, k, nd=2):
    v = r.get(k)
    return "" if v in (None, "", "None", "nan") else (f"{float(v):.{nd}f}" if k not in ("kind", "manoeuvre") else v)


def classes_md(R, cl):
    md = ["# SWV1 part A: collision classes by what the plan's own swept footprint did (generated by scripts/swv1_report.py)", "",
          "Definitions: plans/2026-10-10-swv1-prereg.md, section A, with the three refinements listed in results/swerve_clearance.md. Per-decision rows: `decisions_<dom>.csv`; per rollout: `classes.csv`.", "",
          "| set | n | (i) | (ii) | (iii) | (iv) | (v) | planned sweep intersects the struck object in the last 3 s | median lead time of the first intersecting plan s | median shortfall m | largest planned lateral acceleration m/s^2 | tracking error p95, median m |",
          "|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    for name, st in GROUPS:
        X = [r for r in R if r["set"] in st]
        g = lambda k: [float(r[k]) for r in X if r[k] not in ("", "None", "nan")]  # noqa: E731
        md.append(f"| {name} | {len(X)} | " + " | ".join(f"{sum(r['cls'] == c for r in X)} ({100 * np.mean([r['cls'] == c for r in X]):.0f} %)" for c in COL) +
                  f" | {sum(r['sweep_hit_w3'] == 'True' for r in X)} / {len(X)} | {np.median(g('first_hit_lead_s')):.1f} | {np.median(g('short_med')):.2f} | {max(g('alat_max')):.2f} | {np.median(g('track_p95')):.2f} |")
    md += ["", "## Clips per class (COL1's clip ids, `figs/collisions/`)", "", "| set | class | rollouts (scenes) | clip ids | struck-object kinds (COL1) |", "|:--|:--|--:|:--|:--|"]
    for name, st in GROUPS[:3]:
        for c in COL:
            X = [r for r in R if r["set"] in st and r["cls"] == c]
            if X:
                kd = defaultdict(int)
                for r in X:
                    kd[r["kind"] + (f" [{r['manoeuvre']}]" if r["manoeuvre"] and c == "ii" else "")] += 1
                md.append(f"| {name} | {NAME[c]} | {len(X)} ({len({r['scene'] for r in X})}) | {', '.join(sorted({cl[r['set'], r['scene']] for r in X if (r['set'], r['scene']) in cl})) or '-'} | "
                          f"{'; '.join(f'{k} {v}' for k, v in sorted(kd.items()))} |")
    md += ["", "## Per rollout", "",
           "| set | scene | clip | COL1 kind | class | manoeuvre | ego m/s | offset from logged path m | log turn deg | share of last-3 s plans whose sweep intersects (served / P0) | first intersecting plan, s before impact | shortfall m | max planned a_lat | yaw rate rms demanded / delivered | tracking p95 m |",
           "|:--|:--|:--|:--|:--|:--|--:|--:|--:|:--|--:|--:|--:|:--|--:|"]
    for r in R:
        md.append(f"| {r['set']} | {r['scene'][-8:]} | {cl.get((r['set'], r['scene']), '')} | {r['kind']} | {r['cls']} | {r['manoeuvre']} | {f(r, 'ego_v_ev', 1)} | {f(r, 'lat_ev')} | {f(r, 'log_turn', 0)} | "
                  f"{f(r, 'share_hit_w3')} / {f(r, 'share_hit_w3_p0')} | {f(r, 'first_hit_lead_s', 1)} | {'> 3' if r['short_max3'] == 'True' and not f(r, 'short_med') else f(r, 'short_med')} | {f(r, 'alat_max')} | "
                  f"{f(r, 'yaw_dem_rms', 3)} / {f(r, 'yaw_del_rms', 3)} | {f(r, 'track_p95')} |")
    (OUT / "classes.md").write_text("\n".join(md) + "\n")


def fig_classes(R):
    fig, ax = plt.subplots(figsize=(8.2, 2.9))
    for i, (name, st) in enumerate(GROUPS):
        X = [r for r in R if r["set"] in st]
        x0 = 0
        for c in COL:
            n = sum(r["cls"] == c for r in X)
            if n:
                ax.barh(i, n / len(X) - 0.004, left=x0 + 0.002, color=COL[c], height=0.62, label=NAME[c] if i == 0 or c not in ax.get_legend_handles_labels()[1] else None)
                ax.text(x0 + n / len(X) / 2, i, str(n), ha="center", va="center", color="white", fontsize=9, fontweight="bold")
            x0 += n / len(X)
        ax.text(1.01, i, f"n = {len(X)}", va="center", color=MUTE)
    h, l = ax.get_legend_handles_labels()
    u = dict(zip(l, h))
    ax.legend([u[NAME[c]] for c in COL if NAME[c] in u], [NAME[c] for c in COL if NAME[c] in u], loc="upper center", bbox_to_anchor=(0.5, -0.18), ncol=2, frameon=False, fontsize=8)
    ax.set_yticks(range(len(GROUPS)), [g[0] for g in GROUPS])
    ax.invert_yaxis()
    ax.set_xlim(0, 1.1), ax.set_xticks([0, 0.25, 0.5, 0.75, 1.0], ["0", "25 %", "50 %", "75 %", "100 %"])
    ax.set_title("At-fault collisions by class: no rollout has a planned sweep that clears (class iii is empty)", loc="left", color=INK, fontsize=10)
    fig.savefig(FIG / "fig1_classes.png", dpi=160, bbox_inches="tight")
    plt.close(fig)


def fig_ceiling_signals():
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.9), gridspec_kw=dict(width_ratios=[1, 1.25]))
    ax = axs[0]
    arms = ["lat-acc cap 3.0", "lat-acc cap 1.7", "lead-sweep stop (P0)", "footprint stop (privileged ceiling)", "footprint stop (privileged ceiling), 2 m margin"]
    lab = ["lat-acc cap 3.0 m/s² (openpilot)", "lat-acc cap 1.7 m/s²", "lead-sweep stop (model's lead)", "footprint stop, 0.5 m (privileged)", "footprint stop, 2 m (privileged)"]
    doms = [("nuplan", ("P2H10-F-s0", "P2H10-F-s1"), "nuPlan P2H10-F (22)", "#2a78d6"), ("pai", ("pai-base",), "PAI baseline (12)", "#eb6834")]
    for j, (dom, st, dl, c) in enumerate(doms):
        cf = [r for r in csv.DictReader(open(OUT / f"cf_{dom}.csv")) if r["grp"] == "C" and r["set"] in st]
        for i, a in enumerate(arms):
            x = [r for r in cf if r["arm"] == a]
            v = np.mean([r["avoided"] == "True" for r in x])
            ax.barh(i + (j - 0.5) * 0.36, v, height=0.32, color=c, label=dl if i == 0 else None)
            ax.text(v + 0.015, i + (j - 0.5) * 0.36, f"{sum(r['avoided'] == 'True' for r in x)} / {len(x)}", va="center", color=INK, fontsize=8)
    ax.set_yticks(range(len(arms)), lab)
    ax.invert_yaxis()
    ax.set_xlim(0, 1.12), ax.set_xticks([0, 0.3, 0.5, 1.0], ["0", "30 %", "50 %", "100 %"])
    ax.axvline(0.3, color=MUTE, lw=0.8, ls=":")
    ax.legend(frameon=False, fontsize=8, loc="upper right")
    ax.set_title("B. Collisions avoided, executed path re-timed (kinematic)", loc="left", fontsize=10, color=INK)
    ax = axs[1]
    rows = []
    for dom, grp, c in (("nuplan", "P2H10-F (s0 + s1)", "#2a78d6"), ("pai", "P2H10-F-s0", "#eb6834")):
        for r in csv.DictReader(open(OUT / f"signals_{dom}.csv")):
            if r["read"] == "primary" and r["group"] == grp:
                rows.append((dom, r["signal"], float(r["auc"]), float(r["lo"]), float(r["hi"]), c))
    show = ["lead_sweep_P0", "lead_need_P0", "lead_p_P0", "edge_margin_P0", "lane_exc_P0", "meta_brake_P0", "meta_steer_P0", "desire_lc_P0", "plan_std2_FT", "plan_std2_P0", "base_gap", "alat", "abs_dpsi4",
            "combo", "frozen_ref"]
    for i, sname in enumerate(show):
        for j, dom in enumerate(("nuplan", "pai")):
            x = [r for r in rows if r[0] == dom and r[1] == sname]
            if x:
                _, _, a, lo, hi, c = x[0]
                y = i + (j - 0.5) * 0.34
                ax.plot([lo, hi], [y, y], color=c, lw=2, solid_capstyle="round")
                ax.plot([a], [y], "o", color=c, ms=5, mec=SURF, mew=1, label={"nuplan": "nuPlan P2H10-F", "pai": "PAI baseline"}[dom] if i == 0 else None)
    ax.axvline(0.75, color=MUTE, lw=0.8, ls=":"), ax.axvline(0.65, color=MUTE, lw=0.8, ls=":"), ax.axvline(0.5, color=MUTE, lw=0.6)
    ax.set_yticks(range(len(show)), [s.replace("frozen_ref", "frozen boxes (privileged ref.)") for s in show])
    ax.invert_yaxis()
    ax.set_xlim(0.2, 1.0), ax.set_xlabel("AUC, collision decisions whose planned sweep intersects vs clean decisions (95 % by log)")
    ax.legend(frameon=False, fontsize=8, loc="lower left")
    ax.set_title("C. Non-privileged signals (lines at 0.65 / 0.75)", loc="left", fontsize=10, color=INK)
    fig.tight_layout()
    fig.savefig(FIG / "fig2_ceiling_signals.png", dpi=160, bbox_inches="tight")
    plt.close(fig)


def draw_poly(ax, p, **kw):
    x, y = p.exterior.xy
    ax.fill(x, y, **kw)


def example(r, rows, tag, title, maps, lead_s=(3.0, 2.0, 1.0)):
    D = [d for d in rows if d["set"] == r.set and d["scene"] == r.scene]
    ks = []
    for want in lead_s:
        c = [d for d in D if d["t_to_ev"] > 0.3]
        if c:
            ks.append(min(c, key=lambda d: abs(d["t_to_ev"] - want)))
    ks = list({d["k"]: d for d in ks}.values())
    fig, axs = plt.subplots(1, len(ks), figsize=(4.6 * len(ks), 4.8), squeeze=False)
    te = r.t_ev
    for ax, d in zip(axs[0], ks):
        i = d["k"]
        now, plan = r.now[i], r.plan[i]
        e0 = r.ego_c(now)[0]
        R_ = CL.rot(e0[2] - np.pi / 2)                    # ego heading up
        tf = lambda xy: (np.atleast_2d(xy)[:, :2] - e0[:2]) @ R_  # noqa: E731
        tp = lambda poly: shapely.Polygon(tf(np.array(poly.exterior.coords)))  # noqa: E731
        m = maps.get(r.scene) if maps else None
        if m:
            for ln in m["lanes"]:
                c = tf(ln["center"])
                ax.plot(c[:, 0], c[:, 1], color="#d9d8d2", lw=0.8, zorder=0)
        g = tf(r.path)
        ax.plot(g[:, 0], g[:, 1], color=MUTE, lw=1.0, ls="--", zorder=1, label="logged path")
        tt = np.arange(r.T0, min(te + 2e5, r.T1) + 1, 1e5)
        ex = tf(r.ego_rig(tt))
        ax.plot(ex[:, 0], ex[:, 1], color=INK, lw=1.4, zorder=3, label="driven path")
        eb = S.boxes(S.centre(plan, r.off), r.Le, r.We)
        draw_poly(ax, tp(shapely.unary_union(list(eb)).convex_hull if False else shapely.unary_union(list(eb))) if shapely.unary_union(list(eb)).geom_type == "Polygon" else tp(shapely.unary_union(list(eb)).convex_hull),
                  color="#2a78d6", alpha=0.22, lw=0, zorder=2, label="planned swept ego box (4 s)")
        pc = tf(plan)
        ax.plot(pc[:, 0], pc[:, 1], color="#2a78d6", lw=1.2, zorder=4)
        for k in r.ids:
            p, ok = r.obj_pose(k, now)
            if not ok[0] or np.hypot(*(p[0, :2] - e0[:2])) > 45:
                continue
            b = tp(S.boxes(p, *r.size(k))[0])
            draw_poly(ax, b, color="#eb6834" if k == r.struck else "#b9b8b1", lw=0, zorder=2.5, label="struck object (now)" if k == r.struck else None)
        draw_poly(ax, tp(S.boxes(r.ego_c(now), r.Le, r.We)[0]), color=INK, alpha=0.85, lw=0, zorder=5)
        sw = r.sweep(i, ids=[r.struck])
        if r.struck in sw and sw[r.struck][1] >= 0:
            j = sw[r.struck][1]
            x, y = tp(eb[j]).exterior.xy
            ax.plot(x, y, color="#d03b3b", lw=1.6, zorder=6, label="first planned pose that intersects")
            x, y = tp(S.boxes(r.obj_pose(r.struck, now + j * 1e5)[0], *r.size(r.struck))[0]).exterior.xy
            ax.plot(x, y, color="#eb6834", lw=1.2, ls=":", zorder=6)
        q = None
        try:
            import swv1_a as A
            q = A.p0_plan(r, i)
        except Exception:
            pass
        if q is not None:
            qc = tf(q)
            ax.plot(qc[:, 0], qc[:, 1], color="#008300", lw=1.2, zorder=4, label="shipped weights' plan")
        ax.set_aspect("equal")
        ax.set_xlim(-14, 14), ax.set_ylim(-8, 30)
        ax.set_xticks([]), ax.set_yticks([])
        for s_ in ax.spines.values():
            s_.set_visible(False)
        sh = d.get("short_st")
        ax.set_title(f"{d['t_to_ev']:.1f} s before impact, {d['v_e']:.1f} m/s\n" + (f"planned contact in {d['ti_st']:.1f} s; short by {'> 3' if sh is None or not np.isfinite(sh) else f'{abs(sh):.1f}'} m"
                                                                                  if d["hit_st"] else f"planned sweep clears by {d['clr_st']:.2f} m") + f"; a_lat {d['alat']:.1f} m/s²",
                     fontsize=8.5, color=INK, loc="left")
    h, l = axs[0][-1].get_legend_handles_labels()
    u = dict(zip(l, h))
    fig.legend(u.values(), u.keys(), loc="lower center", ncol=3, frameon=False, fontsize=8)
    fig.suptitle(title, x=0.01, ha="left", fontsize=10, color=INK)
    fig.tight_layout(rect=(0, 0.07, 1, 0.95))
    fig.savefig(FIG / f"ex_{tag}.png", dpi=150, bbox_inches="tight")
    plt.close(fig)


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    R = list(csv.DictReader(open(OUT / "classes.csv")))
    cl = clips()
    classes_md(R, cl)
    fig_classes(R)
    fig_ceiling_signals()
    maps = CL.load(S.TMP / "nuplan/maps.pkl") if (S.TMP / "nuplan/maps.pkl").exists() else {}
    cls = {(r["set"], r["scene"]): r for r in R}
    NU = {(r.set, r.scene[-16:]): r for r in S.nuplan(ctrl=False)}
    PA = {r.scene: r for r in S.pai("base") if r.grp == "C"}
    dn, dp = pickle.load(open(S.TMP / "dec_nuplan.pkl", "rb")), pickle.load(open(S.TMP / "dec_pai.pkl", "rb"))
    EX = [("n07_turn_ii", NU["P2H10-F-s1", "583e9cc4115258e4"], dn, "n07"), ("n05_turn_ii", NU["P2H10-F-s0", "6fc4fc2702305dfa"], dn, "n05"),
          ("n06_drift_iv", NU["P2H10-F-s0", "80f6c94fed0c5519"], dn, "n06"), ("n03_drift_iv", NU["P2H10-F-s0", "6856c3ad77315d3c"], dn, "n03"),
          ("n01_lead_i", NU["P2H10-F-s0", "b5b8d20688385790"], dn, "n01"), ("p07_goaround_ii", PA["0ee89cab"], dp, "pai_p07"), ("p04_tightpass_ii", PA["a28b6685"], dp, "pai_p04"),
          ("p02_goaround_ii", PA["13fb89b9"], dp, "pai_p02")]
    for tag, r, rows, clip in EX:
        c = cls[r.set, r.scene]
        example(r, rows, tag, f"{clip} ({r.set}, {r.scene[-8:]}): class ({c['cls']}){' ' + c['manoeuvre'] if c['manoeuvre'] else ''}, {c['kind']}", maps)
        print("fig", tag)


if __name__ == "__main__":
    main()
