#!/usr/bin/env python3
"""Lane CF1 read-out (plans/2026-10-09-cf1-confirm-prereg.md): P2H10 / YR10m10 / APY10m10 recipes (two-seed per-scene means) on the selection
scenes, Fresh-A (part012-015), Fresh-B (OT3's 400 later scenes) and their unions, with the registered verdicts.

  cf1_report.py --out DIR            (box; plain python3 + numpy; reads ot3/a/manifest.json and cf1/a/manifest.json)
Writes cf1_report.md, cf1_per_scene.csv, cf1_stats.json into --out.
"""
import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import c0b_report as R  # noqa: E402
from ot3_report import ci2, f2  # noqa: E402

RA = Path(__import__("os").environ.get("DATA_DIR", "/root/autodl-tmp/ujs")) / "runs/alpasim"
RECIPES = {"P2H10": "P2H10-F", "YR10m10": "YR10m10-F", "APY10m10": "APY10m10-AB", "AP2H10": "AP2H10-AB"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    o3 = json.loads((RA / "ot3/a/manifest.json").read_text())
    cf = {}
    for st_ in ("a", "b"):
        if (RA / f"cf1/{st_}/manifest.json").exists():
            cf |= json.loads((RA / f"cf1/{st_}/manifest.json").read_text())
    L5 = RA / "c0b/lists"
    A = set((L5 / "cf1fresh.txt").read_text().split())
    Bn = set((L5 / "ot3new.txt").read_text().split())
    S7 = set((L5 / "all.txt").read_text().split())
    sets = {"Fresh-A (part012-015)": A, "Fresh-B (OT3 400)": Bn, "Fresh (791)": A | Bn, "selection (700)": S7, "All (1491)": A | Bn | S7}
    dirs = {}
    for t, r in RECIPES.items():
        for s in (0, 1):
            k = f"{r}-s{s}"
            dirs[k] = o3.get(k, []) + o3.get(k + "@new", []) + cf.get(k + "@new", []) + cf.get(k + "@fresh", [])
    D = {k: R.load_driver(v) for k, v in dirs.items()}
    scenes = sorted(set.union(*(set(D[k][0]) for k in D)))
    cl = np.array([R.log_of(s) for s in scenes])
    nan = np.full(len(scenes), np.nan)
    f = lambda fn: {k: np.array([fn(D[k][0][s]) if s in D[k][0] else np.nan for s in scenes]) for k in D}  # noqa: E731
    sc, ev = f(lambda r: r["score"]), f(lambda r: float((r.get("metrics") or {}).get("offroad_or_collision_at_fault", 0) or 0))
    zc = {k: np.array([R.zclass(D[k][0][s]) if s in D[k][0] else "" for s in scenes]) for k in D}
    nd = {k: np.array([D[k][3].get(s, 0) for s in scenes]) for k in D}
    rec = {t: [f"{r}-s0", f"{r}-s1"] for t, r in RECIPES.items()}
    gs = {t: np.mean([sc[x] for x in v], 0) for t, v in rec.items()}
    # route-fold scenes: zero with no decision for every seed of every recipe that ran there
    fold = [i for i in range(len(scenes)) if all(np.isnan(sc[k][i]) or (sc[k][i] == 0 and nd[k][i] == 0) for k in D) and any(not np.isnan(sc[k][i]) for k in D)]
    st, L = {}, ["# CF1: confirmation read (generated by scripts/cf1_report.py)", ""]
    msk = {n: np.array([s in ss for s in scenes]) for n, ss in sets.items()}
    for n, m in msk.items():
        have = m & np.all([~np.isnan(gs[t]) for t in rec], 0)
        L += [f"## {n}: {int(have.sum())} of {int(m.sum())} scenes have all three recipes, {len(set(cl[have]))} logs", "",
              "| recipe | seeds | mean [95% CI, logs] | 95% CI scenes | zeros | at-fault collision | offroad | left corridor | slow | at-fault events |", "|:--|:--|:--|:--|--:|--:|--:|--:|--:|--:|"]
        st[n] = dict(n=int(have.sum()), logs=len(set(cl[have])), recipes={}, diffs={})
        for t, v in rec.items():
            h = have
            mean = R.ci(gs[t][h], cl[h])
            c2 = ci2(gs[t][h], cl[h])["scene"]
            z = lambda cls: float(np.mean([(zc[x][h] == cls).sum() for x in v]))  # noqa: E731
            zeros = float(np.mean([(sc[x][h] == 0).sum() for x in v]))
            slow = float(np.mean([((sc[x][h] > 0) & (sc[x][h] < 1)).sum() for x in v]))
            evs = float(np.mean([ev[x][h].sum() for x in v]))
            st[n]["recipes"][t] = dict(mean=mean, scene_ci=c2, seeds=[float(sc[x][h].mean()) for x in v], zeros=zeros, slow=slow, events=evs,
                                       **{c: z(c) for c in R.FAIL})
            L.append(f"| {t} | {' / '.join(f'{sc[x][h].mean():.4f}' for x in v)} | {R.fmt(mean)} | [{c2[0]:.4f}, {c2[1]:.4f}] | {zeros:g} | {z('collision_at_fault'):g} | "
                     f"{z('offroad'):g} | {z('left_corridor_laterally'):g} | {slow:g} | {evs:g} |")
        L += ["", "| difference | point | 95% CI scenes | 95% CI logs (decides) | seed 0 / seed 1 differences |", "|:--|--:|:--|:--|:--|"]
        for x, y in (("YR10m10", "P2H10"), ("APY10m10", "P2H10"), ("APY10m10", "YR10m10"), ("AP2H10", "P2H10"), ("APY10m10", "AP2H10"), ("AP2H10", "YR10m10")):
            d = ci2(gs[x][have] - gs[y][have], cl[have])
            sd = [float((sc[rec[x][i]][have] - sc[rec[y][i]][have]).mean()) for i in (0, 1)]
            st[n]["diffs"][f"{x} - {y}"] = dict(**d, per_seed=sd)
            L.append(f"| {x} - {y} | {f2(d)} | {sd[0]:+.4f} / {sd[1]:+.4f} |")
        L.append("")
    pa = st["Fresh-A (part012-015)"]["diffs"]["YR10m10 - P2H10"]
    ver = "confirmed" if pa["mean"] >= 0.005 and pa["log"][0] > 0 else "refuted" if pa["mean"] <= 0 else "inconclusive"
    sa = st["Fresh (791)"]["diffs"]["APY10m10 - YR10m10"]
    cand = sa["mean"] >= 0.005 and sa["log"][0] > 0
    L[2:2] = ["## Registered verdicts", "",
              f"- Primary, YR10m10 - P2H10 on Fresh-A: {pa['mean']:+.4f}, log-clustered CI [{pa['log'][0]:+.4f}, {pa['log'][1]:+.4f}] -> **{ver}** "
              "(confirmed: >= +0.005 and lower bound > 0; refuted: <= 0; else inconclusive).",
              f"- Secondary, APY10m10 - YR10m10 on the 791 fresh scenes: {sa['mean']:+.4f}, log-clustered CI [{sa['log'][0]:+.4f}, {sa['log'][1]:+.4f}] -> "
              f"APY10m10 is {'a candidate' if cand else 'not a candidate'}.", ""]
    ua, ub = st["Fresh (791)"]["diffs"]["APY10m10 - AP2H10"], st["Fresh (791)"]["diffs"]["AP2H10 - P2H10"]
    ub2 = st["All (1491)"]["diffs"]["AP2H10 - P2H10"]
    ok = lambda d: d["mean"] >= 0.005 and d["log"][0] > 0  # noqa: E731
    L[2:2] = ["## Amendment 1 verdicts", "",
              f"- (a) APY10m10 - AP2H10 on 791: {ua['mean']:+.4f} [{ua['log'][0]:+.4f}, {ua['log'][1]:+.4f}] -> the yaw-rate rows {'add on top of the input standard' if ok(ua) else 'add no value (point < +0.005 or CI includes 0)'}.",
              f"- (b) AP2H10 - P2H10 on 791: {ub['mean']:+.4f} [{ub['log'][0]:+.4f}, {ub['log'][1]:+.4f}] -> {'helps' if ok(ub) else 'does not clear the line'}; "
              f"on 1491: {ub2['mean']:+.4f} [{ub2['log'][0]:+.4f}, {ub2['log'][1]:+.4f}] -> {'helps' if ok(ub2) else 'does not clear the line'}.", ""]
    L += [f"## Route-fold scenes (zero, no decision, for every driver that ran there): {len(fold)}", ""] + [f"- {scenes[i]}" for i in fold]
    st["verdict"], st["apy_candidate"], st["fold"] = ver, bool(cand), [scenes[i] for i in fold]
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    with (out / "cf1_per_scene.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["scene", "log", "set"] + [f"{k}|{c}" for k in D for c in ("score", "zero_class", "atfault_events", "n_decisions")])
        for i, s in enumerate(scenes):
            w.writerow([s, cl[i], "A" if s in A else "B" if s in Bn else "sel"] + [x for k in D for x in (sc[k][i], zc[k][i], ev[k][i], nd[k][i])])
    (out / "cf1_stats.json").write_text(json.dumps(st, indent=1, default=float))
    (out / "cf1_report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
