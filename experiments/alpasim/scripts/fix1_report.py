#!/usr/bin/env python3
"""Lane FIX1 read-out (plans/2026-10-09-fix1-prereg.md): serving arms against the base of the same checkout on identical scene lists.

  fix1_report.py --manifest M [M ...] --base LABEL --arms LABEL [LABEL ...] --lists all [ot3new cf1fresh] --out DIR --name NAME
                 [--ref LABEL=manifest.json:key ...] [--pair X:Y ...] [--winner]          (box; python3 + numpy)
Labels are ot2_loop.py manifest labels; a label of several lists is `LABEL` + `LABEL@list`. --ref adds an earlier run of the base
(another checkout) to show the simulator's run-to-run difference on the same lists. --winner applies the registered lines and writes
<out>/WINNER (an arm label or `none`). Writes <name>.md, <name>_per_scene.csv, <name>_stats.json.
"""
import argparse
import csv
import json
import os
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import c0b_report as R  # noqa: E402
from ot3_report import ci2, f2  # noqa: E402

RA = Path(os.environ.get("DATA_DIR", "/root/autodl-tmp/ujs")) / "runs/alpasim"


def serving(dirs):
    """Per scene from drive.jsonl: decisions, decisions with the lead limit lower than the plan, metres cut, median serve ms."""
    out, ms, tot = {}, [], []
    for D in map(Path, dirs):
        f = D / "driver-logs/drive.jsonl"
        if not f.exists():
            continue
        for line in f.open():
            if '"drive"' not in line:
                continue
            x = json.loads(line)
            if x.get("kind") != "drive":
                continue
            o = out.setdefault(x["scene"], dict(n=0, cut=0, cut_m=0.0, present=0))
            o["n"] += 1
            tot.append(x["ms"]["total"])
            fx = x.get("fix")
            if fx:
                ms.append(fx.get("ms", 0.0))
                li = fx.get("lead")
                if li:
                    o["cut"] += li["cut"] >= 0.5
                    o["cut_m"] += li["cut"]
                    o["present"] += li["d"] is not None
    return out, (float(np.median(ms)) if ms else 0.0, float(np.percentile(ms, 99)) if ms else 0.0), (float(np.median(tot)), float(np.percentile(tot, 90)), float(np.percentile(tot, 99))) if tot else (0, 0, 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", nargs="+", required=True), ap.add_argument("--base", required=True), ap.add_argument("--arms", nargs="+", required=True)
    ap.add_argument("--lists", nargs="+", default=["all"]), ap.add_argument("--out", required=True), ap.add_argument("--name", default="fix1")
    ap.add_argument("--ref", action="append", default=[]), ap.add_argument("--pair", action="append", default=[]), ap.add_argument("--winner", action="store_true")
    a = ap.parse_args()
    man = {}
    for m in a.manifest:
        man |= json.loads(Path(m).read_text())
    want = set().union(*(set((RA / "c0b/lists" / f"{l}.txt").read_text().split()) for l in a.lists))
    dirs = {k: [d for key in man if key == k or key.startswith(k + "@") for d in man[key]] for k in [a.base] + a.arms}
    for r in a.ref:
        lab, src = r.split("=", 1)
        f, key = src.rsplit(":", 1)
        mm = json.loads(Path(f).read_text())
        dirs[lab] = [d for k in mm if k == key or k.startswith(key + "@") for d in mm[k]]
    D = {k: R.load_driver(v) for k, v in dirs.items() if v}
    SV = {k: serving(dirs[k]) for k in D}
    scenes = sorted(s for s in want if all(s in D[k][0] for k in D))
    cl = np.array([R.log_of(s) for s in scenes])
    sc = {k: np.array([D[k][0][s]["score"] for s in scenes]) for k in D}
    zc = {k: np.array([R.zclass(D[k][0][s]) for s in scenes]) for k in D}
    ev = {k: np.array([float((D[k][0][s].get("metrics") or {}).get("offroad_or_collision_at_fault", 0) or 0) for s in scenes]) for k in D}
    L = [f"# FIX1 {a.name}: serving arms against the base (generated by scripts/fix1_report.py)", "",
         f"{len(scenes)} of {len(want)} scenes scored by every run, {len(set(cl))} logs. Lists: {', '.join(a.lists)}. Slow = 0 < score < 1.", "",
         "| run | mean [95% CI, logs] | zeros | at-fault collision | offroad | left corridor | other | slow | at-fault events | decisions with the lead limit cutting >= 0.5 m | scenes with such a decision | serve ms median / p99 | drive ms median / p90 / p99 |",
         "|:--|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|:--|"]
    st = dict(n=len(scenes), logs=len(set(cl)), runs={}, diffs={}, dirs=dirs)
    for k in D:
        z = {c: int((zc[k] == c).sum()) for c in R.FAIL + ("other",)}
        sv, ms, tot = SV[k]
        cutd = sum(sv.get(s, {}).get("cut", 0) for s in scenes)
        cuts = sum(sv.get(s, {}).get("cut", 0) > 0 for s in scenes)
        st["runs"][k] = dict(mean=R.ci(sc[k], cl), zeros=int((sc[k] == 0).sum()), slow=int(((sc[k] > 0) & (sc[k] < 1)).sum()), events=float(ev[k].sum()), **z,
                             cut_decisions=int(cutd), cut_scenes=int(cuts), serve_ms=ms, drive_ms=tot)
        r = st["runs"][k]
        L.append(f"| {k} | {R.fmt(r['mean'])} | {r['zeros']} | {z['collision_at_fault']} | {z['offroad']} | {z['left_corridor_laterally']} | {z['other']} | {r['slow']} | {r['events']:g} | "
                 f"{cutd} | {cuts} | {ms[0]:.2f} / {ms[1]:.2f} | {tot[0]:.1f} / {tot[1]:.1f} / {tot[2]:.1f} |")
    pairs = [(x, a.base) for x in a.arms if x in D] + [tuple(p.split(":")) for p in a.pair] + [(lab.split("=")[0], a.base) for lab in a.ref]
    L += ["", "| difference | point | 95% CI scenes | 95% CI logs | zero -> non-zero | non-zero -> zero | at-fault collision zeros | slow | scenes changed by > 0.05 |", "|:--|--:|:--|:--|--:|--:|:--|:--|--:|"]
    for x, y in pairs:
        if x not in D or y not in D:
            continue
        d = ci2(sc[x] - sc[y], cl)
        fixed, broke = int(((sc[y] == 0) & (sc[x] > 0)).sum()), int(((sc[y] > 0) & (sc[x] == 0)).sum())
        st["diffs"][f"{x} - {y}"] = dict(**d, fixed=fixed, broke=broke)
        L.append(f"| {x} - {y} | {f2(d)} | {fixed} | {broke} | {st['runs'][y]['collision_at_fault']} -> {st['runs'][x]['collision_at_fault']} | "
                 f"{st['runs'][y]['slow']} -> {st['runs'][x]['slow']} | {int((np.abs(sc[x] - sc[y]) > 0.05).sum())} |")
    if a.winner:
        b, kept = st["runs"][a.base], {}
        L += ["", "## Registered lines (each arm against the base)", "", "| arm | at-fault collision zeros drop | difference >= 0 | log-clustered lower bound > -0.005 | slow <= 1.1 x base | kept | gain (>= +0.005, lower bound > 0) |", "|:--|:--|:--|:--|:--|:--|:--|"]
        for x in a.arms:
            if x not in D:
                continue
            r, d = st["runs"][x], st["diffs"][f"{x} - {a.base}"]
            c = [r["collision_at_fault"] < b["collision_at_fault"], d["mean"] >= 0, d["log"][0] > -0.005, r["slow"] <= 1.1 * b["slow"]]
            gain = d["mean"] >= 0.005 and d["log"][0] > 0
            if all(c):
                kept[x] = d["mean"]
            st["diffs"][f"{x} - {a.base}"].update(kept=all(c), gain=bool(gain), lines=[bool(v) for v in c])
            L.append(f"| {x} | {b['collision_at_fault']} -> {r['collision_at_fault']}: {'yes' if c[0] else 'no'} | {d['mean']:+.4f}: {'yes' if c[1] else 'no'} | {d['log'][0]:+.4f}: {'yes' if c[2] else 'no'} | "
                     f"{b['slow']} -> {r['slow']}: {'yes' if c[3] else 'no'} | **{'kept' if all(c) else 'not kept'}** | {'gain' if gain else 'no'} |")
        win = max(kept, key=lambda k: (round(kept[k], 6), -len(k))) if kept else "none"
        st["winner"] = win
        L += ["", f"Winning configuration (the kept arm with the largest difference; a tie goes to fewer switches): **{win}**"]
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    if a.winner:
        (out / "WINNER").write_text(st["winner"] + "\n")
    with (out / f"{a.name}_per_scene.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["scene", "log"] + [f"{k}|{c}" for k in D for c in ("score", "zero_class", "atfault_events", "lead_cut_decisions", "lead_cut_m")])
        for i, s in enumerate(scenes):
            w.writerow([s, cl[i]] + [x for k in D for x in (sc[k][i], zc[k][i], ev[k][i], SV[k][0].get(s, {}).get("cut", 0), round(SV[k][0].get(s, {}).get("cut_m", 0.0), 2))])
    (out / f"{a.name}_stats.json").write_text(json.dumps(st, indent=1, default=float))
    (out / f"{a.name}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
