#!/usr/bin/env python3
"""Lane FIX1, PAI track on the GPU box (prereg amendment 3).
  prune <run dir>     delete videos, the renderer cache and every rollout.asl except those of zero-score rollouts of the +a+b stacks (84 stacks x 2.5 GB of zero-score logs would not fit the disk; stdlib only)
  table --base <PAI2 base dir: <chunk>_s<seed>/> --runs <dir: <arm>_<chunk>_s<seed>/> --chunks <dir of chunk lists> --out DIR   (numpy)
Table: per arm and seed the mean scene score and zeros by flag; the two-seed per-scene mean against the base with a scene-resampled 95 %
bootstrap interval (10 000 draws, seed 0); counts of zero <-> non-zero changes; the Tokyo lists (40) and the extension (20) separately.
"""
import json
import shutil
import sys
from pathlib import Path

FAIL = ("collision_at_fault", "offroad", "left_corridor_laterally")
ARMS = ("a", "b", "ab", "c1", "c2", "c1b", "c2b")
CHUNKS = ("a10", "b1", "b2a", "b2b", "e1", "e2")


def rollouts(d: Path) -> dict:
    return {r["clipgt_id"]: r for r in json.loads((d / "aggregate/results-summary.json").read_text())["rollouts"]}


def prune(d: Path):
    shutil.rmtree(d / "nre-cache", ignore_errors=True)
    try:
        R = rollouts(d)
    except Exception:
        R = {}
    for f in d.glob("rollouts/*/*/*.mp4"):
        f.unlink()
    for f in d.glob("rollouts/*/*/rollout.asl"):
        r = R.get(f.parts[-3])
        if r is not None and (r["score"] > 0 or not d.name.startswith("ab_")):      # disk: zero-score logs are kept for the +a+b stacks only
            f.unlink()


def table(a):
    import numpy as np
    base, runs, out = Path(a["--base"]), Path(a["--runs"]), Path(a["--out"])
    ch = {c: (Path(a["--chunks"]) / f"{c}.txt").read_text().split() for c in CHUNKS}
    scenes = [s for c in CHUNKS for s in ch[c]]
    sub = {"all 60": scenes, "Tokyo lists (40)": [s for c in CHUNKS[:4] for s in ch[c]], "untouched by any design choice (b2a, b2b, e1, e2: 40)": [s for c in ("b2a", "b2b", "e1", "e2") for s in ch[c]],
           "extension (e1, e2: 20)": ch["e1"] + ch["e2"]}
    D, miss = {}, []
    for arm in ("base",) + ARMS:
        for s in (0, 1):
            R = {}
            for c in CHUNKS:
                d = (base / f"{c}_s{s}") if arm == "base" else (runs / f"{arm}_{c}_s{s}")
                try:
                    R |= rollouts(d)
                except Exception:
                    miss.append(d.name if arm != "base" else f"base {d.name}")
            D[arm, s] = R
    sc = lambda k, S: np.array([D[k].get(x, {}).get("score", np.nan) for x in S])  # noqa: E731
    cls = lambda r: next((f for f in FAIL if r["score_metrics"].get(f)), "other" if r["score"] == 0 else "")  # noqa: E731
    L = ["# FIX1 on the PAI track, GPU box: serving arms for P2H10-F-s0 / -s1 on 60 scenes (generated by scripts/fix1_pai_box_report.py)", "",
         "One rollout per scene, arm and seed. Base = lane PAI2's runs. Missing stacks: " + (", ".join(miss) or "none") + ".", ""]
    st = {}
    for n, S in sub.items():
        L += [f"## {n}", "", "| arm | seed 0 mean | seed 1 mean | two-seed mean | difference to base [95% CI, scenes] | zeros s0 / s1 | at-fault collision | offroad | left corridor | slow | zero -> non-zero | non-zero -> zero | scenes |",
              "|:--|--:|--:|--:|:--|:--|:--|:--|:--|:--|:--|:--|--:|"]
        for arm in ("base",) + ARMS:
            x = [sc((arm, s), S) for s in (0, 1)]
            b = [sc(("base", s), S) for s in (0, 1)]
            okm = ~np.isnan(x[0]) & ~np.isnan(x[1]) & ~np.isnan(b[0]) & ~np.isnan(b[1])
            if not okm.any():
                continue
            m, mb = (x[0] + x[1])[okm] / 2, (b[0] + b[1])[okm] / 2
            d = m - mb
            bs = d[np.random.default_rng(0).integers(0, len(d), (10000, len(d)))].mean(1)
            z = lambda f: " / ".join(str(sum(cls(D[arm, s][q]) == f for q, o in zip(S, okm) if o)) for s in (0, 1))  # noqa: E731
            fl = lambda u, v: " / ".join(str(int((u(b[s][okm]) & v(x[s][okm])).sum())) for s in (0, 1))  # noqa: E731
            st[f"{n}|{arm}"] = dict(mean=float(m.mean()), diff=float(d.mean()), ci=[float(v) for v in np.percentile(bs, [2.5, 97.5])], n=int(okm.sum()), seeds=[float(x[s][okm].mean()) for s in (0, 1)])
            L.append(f"| {arm} | {x[0][okm].mean():.4f} | {x[1][okm].mean():.4f} | {m.mean():.4f} | " + ("" if arm == "base" else f"{d.mean():+.4f} [{np.percentile(bs, 2.5):+.4f}, {np.percentile(bs, 97.5):+.4f}]")
                     + f" | {' / '.join(str(int((x[s][okm] == 0).sum())) for s in (0, 1))} | {z('collision_at_fault')} | {z('offroad')} | {z('left_corridor_laterally')} | "
                     + " / ".join(str(int(((x[s][okm] > 0) & (x[s][okm] < 1)).sum())) for s in (0, 1)) + " | "
                     + ("| " if arm == "base" else f"{fl(lambda u: u == 0, lambda v: v > 0)} | {fl(lambda u: u > 0, lambda v: v == 0)} ") + f"| {int(okm.sum())} |")
        L.append("")
    L += ["## Per scene (score seed 0 / seed 1)", "", "| scene | chunk | " + " | ".join(("base",) + ARMS) + " |", "|:--|:--|" + ":--|" * (1 + len(ARMS))]
    for c in CHUNKS:
        for x in ch[c]:
            L.append(f"| {x[7:15]} | {c} | " + " | ".join(" / ".join((f"{D[arm, s][x]['score']:.2f}" + ("" if D[arm, s][x]["score"] > 0 else {"collision_at_fault": "c", "offroad": "o", "left_corridor_laterally": "l", "other": "?"}[cls(D[arm, s][x])]))
                                                                           if x in D[arm, s] else "-" for s in (0, 1)) for arm in ("base",) + ARMS) + " |")
    L += ["", "Zero classes: c = at-fault collision, o = offroad, l = left corridor.", "", "## Driver (all stacks of an arm)", "",
          "| arm | sessions | inference errors | input errors | `drive` ms median / p90 / p99 | serving step ms median / p99 | decisions with a lead present | lead limit cuts >= 0.5 m | decisions standing (< 0.3 m/s) |", "|:--|--:|--:|--:|:--|:--|:--|--:|:--|"]
    for arm in ARMS:
        tot, ms, n, ie, ip, pres, cut, stand, nfx = [], [], 0, 0, 0, 0, 0, 0, 0
        for d in runs.glob(f"{arm}_*_s[01]"):
            f = d / "driver-logs/drive.jsonl"
            if not f.exists():
                continue
            for line in f.open():
                r = json.loads(line)
                if r.get("kind") == "close":
                    n, ie, ip = n + 1, ie + r["inference_error"], ip + r["input_error"]
                elif r.get("kind") == "drive" and r.get("infer"):
                    tot.append(r["total_ms"])
                    fx = r.get("fix")
                    if fx:
                        nfx += 1
                        ms.append(fx.get("ms", 0.0))
                        stand += fx["v0"] < 0.3
                        if "lead" in fx:
                            pres += fx["lead"]["d"] is not None
                            cut += fx["lead"]["cut"] >= 0.5
        if tot:
            L.append(f"| {arm} | {n} | {ie} | {ip} | {np.median(tot):.1f} / {np.percentile(tot, 90):.1f} / {np.percentile(tot, 99):.1f} | {np.median(ms):.2f} / {np.percentile(ms, 99):.2f} | "
                     f"{pres} of {nfx} | {cut} | {stand} of {nfx} |")
    out.mkdir(parents=True, exist_ok=True)
    (out / "fix1_pai_box.md").write_text("\n".join(L) + "\n")
    (out / "fix1_pai_box_stats.json").write_text(json.dumps(st, indent=1))
    print("\n".join(L))


if __name__ == "__main__":
    if sys.argv[1] == "prune":
        prune(Path(sys.argv[2]))
    else:
        table(dict(zip(sys.argv[2::2], sys.argv[3::2])))
