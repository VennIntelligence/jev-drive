#!/usr/bin/env python3
"""Lane FIX1, PAI track (plans/2026-10-09-fix1-prereg.md): the serving arms against the baseline on the 40 scenes, from pai_run.sh run
dirs. Counts and per-scene changes only (40 scenes carry no interval worth a line).
  fix1_pai_report.py --arm base=<dir>,<dir>,... --arm a=... --arm b=... --arm ab=... --ref <dir with <subject>.json>
                     --subset untouched=<scene list>[,<scene list>] --out <md>          (Tokyo box; python3 + numpy)
The first --arm is the baseline. A scene is reported when every arm scored it.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pai_report as P  # noqa: E402


def load(dirs):
    R, D, C, meta = {}, [], [], []
    for d in map(Path, dirs):
        R |= P.rollouts(d)
        dr, cl = P.drive_log(d)
        D += dr
        C += cl
        if (d / "run.json").exists():
            meta.append(json.loads((d / "run.json").read_text()))
    return R, D, C, meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", action="append", required=True), ap.add_argument("--ref", required=True), ap.add_argument("--subset", action="append", default=[])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    arms = {k: v.split(",") for k, v in (x.split("=", 1) for x in a.arm)}
    A = {k: load(v) for k, v in arms.items()}
    base = next(iter(arms))
    ref = P.refs(Path(a.ref))
    scenes = sorted(set.intersection(*(set(v[0]) for v in A.values())))
    subs = {"all scored scenes": set(scenes)}
    for s in a.subset:
        n, fs = s.split("=", 1)
        subs[n] = set().union(*(set(Path(f).read_text().split()) for f in fs.split(","))) & set(scenes)
    L = ["# FIX1 on the PAI track: serving arms against the baseline (generated by scripts/fix1_pai_report.py)", "",
         "One rollout per scene and arm; the simulator's repeatability on this track is not known. Counts and per-scene changes, no interval.", ""]
    for n, S in subs.items():
        S = sorted(S)
        L += [f"## {n}: {len(S)} scenes", "", "| Row | Mean scene score | Score 1 | Zeros | at-fault collision | offroad | left corridor | Slow (0 < s < 1) | zero -> non-zero vs base | non-zero -> zero | up > 0.05 | down > 0.05 |",
              "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
        sb = np.array([A[base][0][x]["score"] for x in S])
        for k, (R, *_) in A.items():
            s = np.array([R[x]["score"] for x in S])
            zk = [[f for f in P.FAIL if R[x]["score_metrics"].get(f)] for x in S]
            L.append(f"| **{k}** | {s.mean():.4f} | {(s >= 1).sum()} | {(s == 0).sum()} | " + " | ".join(str(sum(f in z for z in zk)) for f in P.FAIL) + f" | {((s > 0) & (s < 1)).sum()} | "
                     + ("| | | |" if k == base else f"{((sb == 0) & (s > 0)).sum()} | {((sb > 0) & (s == 0)).sum()} | {(s - sb > 0.05).sum()} | {(sb - s > 0.05).sum()} |"))
        for k, v in ref.items():
            if all(x in v for x in S):
                s = np.array([np.mean([r["score"] for r in v[x]]) for x in S])
                m = sum(len(v[x]) for x in S)
                fr = [sum(bool(r["score_metrics"].get(f)) for x in S for r in v[x]) / m for f in P.FAIL]
                L.append(f"| {k} (reference, mean of 3) | {s.mean():.4f} | {(s >= 1).sum()} | {(s == 0).sum()} | " + " | ".join(f"{x:.0%}" for x in fr) + " | | | | | |")
        L.append("")
    rm = lambda x: np.mean([np.mean([r["score"] for r in v[x]]) for v in ref.values() if x in v])  # noqa: E731
    tag = lambda x: ",".join(n for n in list(subs)[1:] if x in subs[n])  # noqa: E731
    L += ["## Per scene", "", "| Scene | set | Reference mean | alpamayo1 | " + " | ".join(f"{k} | why" for k in A) + " | GT distance m | " + " | ".join(f"{k} driven m" for k in A) + " |",
          "|---|---|--:|--:|" + "--:|---|" * len(A) + "--:|" + "--:|" * len(A)]
    for x in sorted(scenes, key=rm):
        al = np.mean([r["score"] for r in ref["alpamayo1"][x]]) if x in ref.get("alpamayo1", {}) else float("nan")
        L.append(f"| {x[7:15]} | {tag(x)} | {rm(x):.2f} | {al:.2f} | " + " | ".join(f"{R[x]['score']:.2f} | {P.why(R[x])}" for R, *_ in A.values())
                 + f" | {A[base][0][x]['score_metrics'].get('gt_dist_traveled_m', float('nan')):.0f} | "
                 + " | ".join(f"{(R[x].get('metrics') or {}).get('dist_traveled_m', float('nan')):.0f}" for R, *_ in A.values()) + " |")
    L += ["", "## Driver", "", "| arm | sessions | inference errors | input errors | `drive` ms median / p90 / p99 / max | serving step ms median / p99 | decisions with a lead present | lead limit cuts >= 0.5 m | decisions standing (< 0.3 m/s) | runs |",
          "|---|--:|--:|--:|:--|:--|--:|--:|--:|:--|"]
    for k, (R, D, C, meta) in A.items():
        inf = [r for r in D if r.get("infer")]
        tot = np.array([r["total_ms"] for r in inf]) if inf else np.zeros(1)
        fx = [r["fix"] for r in inf if r.get("fix")]
        ms = np.array([f["ms"] for f in fx if "ms" in f]) if fx else np.zeros(1)
        ld = [f["lead"] for f in fx if "lead" in f]
        v0 = np.array([f["v0"] for f in fx]) if fx else np.zeros(1)
        L.append(f"| {k} | {len(C)} | {sum(c['inference_error'] for c in C)} | {sum(c['input_error'] for c in C)} | "
                 f"{np.median(tot):.1f} / {np.percentile(tot, 90):.1f} / {np.percentile(tot, 99):.1f} / {tot.max():.0f} | {np.median(ms):.2f} / {np.percentile(ms, 99):.2f} | "
                 + (f"{sum(l['d'] is not None for l in ld)} of {len(ld)} | {sum(l['cut'] >= 0.5 for l in ld)} | " if ld else " | | ")
                 + (f"{int((v0 < 0.3).sum())} of {len(fx)}" if fx else "") + f" | {len(meta)} runs, wall {sum(m['wall_s'] for m in meta)} s |")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
