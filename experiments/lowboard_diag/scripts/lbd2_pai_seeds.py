#!/usr/bin/env python3
"""LOWDIAG2: PAI cross-seed tables from the per-seed unit tables of the frozen scripts (lbd_pai.py units).
  python experiments/lowboard_diag/scripts/lbd2_pai_seeds.py   (reads results/pai/units.csv = seed 0, results/pai_s{1,2,3}/units.csv)
Writes results/seeds_pai.md and results/seeds_pai_scenes.csv. No new definition: every class comes from the units' own `cls`, `raw`, `c_sub`."""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

R = Path(__file__).resolve().parents[1] / "results"
SEEDS = [0, 1, 2, 3]
f = lambda d, s: d.raw.fillna("").str.split("+").map(lambda x: s in x)  # noqa: E731


def load(s):
    d = pd.read_csv(R / ("pai/units.csv" if s == 0 else f"pai_s{s}/units.csv"))
    d["seed"] = s
    return d


def first_reg(z):
    """Zeros re-classed with the first registration: no L5, no O2a, original O2c cannot be recomputed (kept as in the final table)."""
    other = f(z, "O1") | f(z, "O2c")
    lon = f(z, "L1") | f(z, "L2")
    rt = f(z, "R1") | f(z, "R2") | (z.K == "corridor")
    return np.where(other, "other", np.where(lon, "longitudinal", np.where(rt, "route", "clearance")))


def fine(r):
    if r.score >= 1:
        return "pass"
    if r.score > 0:
        return "progress loss"
    raw = set(str(r.raw).split("+"))
    sub = str(r.c_sub) if isinstance(r.c_sub, str) else ""
    if "O2a" in raw:
        return "other: spin"
    if r.cls == "other":
        return "other: " + ("rear-ended" if "O2c" in raw else "driver exception" if "O1" in raw else "other")
    if "L5" in raw:
        return "longitudinal: overran logged stop"
    if "L2" in raw and r.cls == "longitudinal":
        return "longitudinal: fast turn entry"
    if r.cls == "longitudinal":
        return "longitudinal: " + ("L1 contact" if "L1" in raw else "other")
    if sub.startswith("2"):
        return "route: command inert"
    if sub.startswith("3"):
        return "route: turn made late"
    if sub.startswith("4"):
        return "route: straight drift"
    if sub.startswith("1"):
        return "route: info missing"
    return r.cls


def main():
    D = {s: load(s) for s in SEEDS if (R / ("pai/units.csv" if s == 0 else f"pai_s{s}/units.csv")).exists()}
    S = sorted(D)
    L = ["# LOWDIAG2, PAI: seed spread of the decision-237 taxonomy (generated by lbd2_pai_seeds.py)\n"]
    P = L.append
    rows = []
    for s in S:
        d = D[s]
        z = d[d.score == 0]
        lost = d.lost.sum()
        spin = f(z, "O2a")
        cs = z.c_sub.fillna("")
        fr = pd.Series(first_reg(z), index=z.index)
        rows.append(dict(seed=s, mean_score=round(1 - lost / len(d), 4), zeros=len(z), lost=round(lost, 2),
                         other=int((z.cls == "other").sum()), long_zeros=int((z.cls == "longitudinal").sum()), progress_loss=int(((d.score > 0) & (d.score < 1)).sum()),
                         route=int((z.cls == "route").sum()), clearance=int((z.cls == "clearance").sum()),
                         share_long=round((z[z.cls == "longitudinal"].lost.sum() + d[(d.score > 0) & (d.score < 1)].lost.sum()) / lost, 3),
                         share_route=round(z[z.cls == "route"].lost.sum() / lost, 3), share_clear=round(z[z.cls == "clearance"].lost.sum() / lost, 3), share_other=round(z[z.cls == "other"].lost.sum() / lost, 3),
                         corridor_zeros=int(z["flags"].str.contains("corridor").sum()), overran=int(f(z, "L5").sum()), spins=int(spin.sum()),
                         command_inert=int(cs.str.startswith("2").sum()), turn_late=int(cs.str.startswith("3").sum()), route_info_missing=int(cs.str.startswith("1").sum()),
                         drift=int((cs.str.startswith("4") & ~spin).sum()), fast_entry=int((f(z, "L2") & ~f(z, "L5")).sum()), L1_contact=int(f(z, "L1").sum()),
                         first_other=int((fr == "other").sum()), first_long=int((fr == "longitudinal").sum()), first_route=int((fr == "route").sum()), first_clear=int((fr == "clearance").sum())))
    T = pd.DataFrame(rows)
    T.to_csv(R / "seeds_pai_counts.csv", index=False)
    P("## Per-seed counts (served `JEV_VCONT=1.0 JEV_LEAD=1`, 60 scenes; seed 0 is decision 237's table)\n")
    P(T.set_index("seed").T.to_markdown() + "\n")
    key = ["zeros", "other", "long_zeros", "progress_loss", "route", "clearance", "overran", "fast_entry", "drift", "command_inert", "turn_late", "spins", "L1_contact", "share_long", "share_route", "share_clear", "share_other", "mean_score"]
    P("## Seed spread of each class count\n\n| quantity | " + " | ".join(f"s{s}" for s in S) + " | min - max | mean | s0 inside the range of the other seeds |\n|:--|" + "--:|" * (len(S) + 3))
    for k in key:
        v = T.set_index("seed")[k]
        oth = v.drop(0) if 0 in S else v
        P(f"| {k} | " + " | ".join(str(v[s]) for s in S) + f" | {v.min()} - {v.max()} | {v.mean():.2f} | {'yes' if len(oth) and oth.min() <= v.get(0, np.nan) <= oth.max() else 'no'} |")
    # per scene
    A = pd.concat(D.values())
    A["label"] = A.apply(fine, axis=1)
    A["coarse"] = A.apply(lambda r: "pass" if r.score >= 1 else "progress loss" if r.score > 0 else r.cls, axis=1)
    piv = A.pivot(index="scene", columns="seed", values="label")
    pc = A.pivot(index="scene", columns="seed", values="coarse")
    sc = A.pivot(index="scene", columns="seed", values="score")
    piv["modal_fine"] = piv[S].mode(axis=1)[0]
    piv["n_same_fine"] = [int((piv.loc[i, S] == piv.loc[i, "modal_fine"]).sum()) for i in piv.index]
    piv["modal_coarse"] = pc[S].mode(axis=1)[0]
    piv["n_same_coarse"] = [int((pc.loc[i, S] == piv.loc[i, "modal_coarse"]).sum()) for i in piv.index]
    piv["n_zero"] = (sc[S] == 0).sum(axis=1)
    piv.to_csv(R / "seeds_pai_scenes.csv")
    P(f"\n## Per-scene agreement ({len(S)} seeds, {len(piv)} scenes)\n")
    P("Scenes by how many seeds put them in the same class (coarse = pass / progress loss / the four classes; fine = the sub-classes of decision 237).\n")
    P("| seeds in the same class | " + " | ".join(str(k) for k in range(len(S), 0, -1)) + " |\n|:--|" + "--:|" * len(S))
    P("| coarse | " + " | ".join(str(int((piv.n_same_coarse == k).sum())) for k in range(len(S), 0, -1)) + " |")
    P("| fine | " + " | ".join(str(int((piv.n_same_fine == k).sum())) for k in range(len(S), 0, -1)) + " |\n")
    P("Zero in k seeds: " + ", ".join(f"k={k}: {int((piv.n_zero == k).sum())}" for k in range(len(S) + 1)) + "\n")
    P("Fine label of the scenes that are a zero in at least one seed and carry the key classes (modal label, seeds agreeing, seeds with a zero):\n")
    kk = piv[piv.modal_fine.str.contains("overran|fast turn|drift|inert|late|spin|L1")].sort_values(["modal_fine", "n_same_fine"], ascending=[True, False])
    P("| scene | " + " | ".join(f"s{s}" for s in S) + " | modal | agree |\n|:--|" + ":--|" * len(S) + ":--|--:|")
    for i, r in kk.iterrows():
        P(f"| {i} | " + " | ".join(str(r[s]) for s in S) + f" | {r.modal_fine} | {r.n_same_fine} |")
    # agreement within the key classes: of the (scene, seed) cells with the label, how many scenes recur
    P("\nRecurrence of each key label: scenes with the label in >= 1 seed, in >= 2 seeds, in all seeds; total (scene, seed) cells.\n")
    P("| label | cells | scenes >= 1 seed | scenes >= 2 | scenes in all |\n|:--|--:|--:|--:|--:|")
    for lab in sorted(set(A.label) - {"pass"}):
        c = (piv[S] == lab).sum(axis=1)
        P(f"| {lab} | {int(c.sum())} | {int((c >= 1).sum())} | {int((c >= 2).sum())} | {int((c == len(S)).sum())} |")
    (R / "seeds_pai.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
